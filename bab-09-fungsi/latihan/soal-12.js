const tambah = (a, b) => a + b;
const kurang = (c, d) => c - d;
const kali = (e, f) => e * f;
const bagi = (g, h) => g / h;

console.log('Tambah : ', tambah(7, 8));
console.log('Kurang : ', kurang(10, 5));
console.log('Kali   : ', kali(25, 2));
console.log('Bagi   : ', bagi(8, 4));
console.log(10 == "10");            //true
console.log(10 === "10");           //false
console.log(false == 0);            //true  
console.log(false === 0);           //false
console.log(null == undefined);     //true
console.log(null === undefined);    //false

//karena == (si santai) operator ini cuma peduli sama nilai nya, dan ga peduli tipe data nya beda apa nggak
//yang satu lagi === (si ketat) operator ini ketat banget karena nilai dan tipe data nya harus sama 